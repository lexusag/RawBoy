// Writes ios/EngineTests/EditsFixtures.swift: edits JSON produced by the web's Edits.ts, which the Swift port
// (ios/Engine/.../develop/Edits.swift) must parse. Run from the repo root:
//   web/node_modules/.bin/vite-node tools/edits_fixtures/generate.ts
// (vite-node resolves the web's TypeScript; no build needed). Re-run when Edits.ts or its parts change.
import { writeFileSync } from 'node:fs';
import { DEFAULT_PARAMS } from '../../web/src/engine/develop/DevelopParams';
import { encodeEdits } from '../../web/src/engine/develop/Edits';
import { newBrushLayer, newRadialLayer, newLinearLayer } from '../../web/src/engine/develop/Masks';
import { newLightLeak } from '../../web/src/engine/develop/LightLeaks';
import { newLightEffect } from '../../web/src/engine/develop/LightEffects';
import { newHealSpot } from '../../web/src/engine/develop/HealSpots';

const defaults = { ...DEFAULT_PARAMS, temperature: 5200, tint: 4 };

const brush = newBrushLayer('Sky');
const radial = newRadialLayer('Face');
const linear = newLinearLayer();
const leak = { ...newLightLeak(0.3, 0.6, 'glow'), seed: 0.123, texture: 40, cover: 25, bend: -30, radii: [1, 1.2, 1, 0.8, 1, 1.1, 1, 0.9] };
const fx = { ...newLightEffect('sparks', 0.5, 0.5), seed: 0.123456789 };

const cases: Record<string, unknown> = {
  basic: { ...defaults, exposure: 0.7, contrast: -12, saturation: 15, temperature: 6100, tint: -3, toneMapper: 'filmic', denoise: 20, sharpening: 33.3 },
  geometry: {
    ...defaults, rotation: 3, flipHorizontal: true, straighten: -4.5, perspectiveVertical: 12, perspectiveHorizontal: -7, scale: 110,
    cropLeft: 0.1, cropTop: 0.05, cropRight: 0.9, cropBottom: 0.8,
  },
  looks: {
    ...defaults, lut: 'portra400', lutAmount: 60, colorDenoise: 35, lensProfile: false, anamorphicGhosts: true, anamorphicColor: 'magenta',
    curves: { rgb: [[0, 0], [0.3, 0.25], [0.8, 0.9], [1, 1]], red: [[0, 0], [1, 1]], green: [[0, 0.05], [1, 1]], blue: [[0, 0], [1, 0.95]] },
  },
  film: { ...defaults, film: 'kodachrome64', filmAmount: 80, filmGrain: 100, halation: 150 },
  masks: {
    ...defaults,
    masks: [
      { ...brush, adjust: { ...brush.adjust, exposure: -0.5, lensBlur: 30, retouch: 20 }, strokes: [
        { id: 's1', erase: false, auto: true, radius: 0.04, hardness: 60, flow: 80, points: [0.123456789, 0.2, 0.3333333, 0.4, 0.5, 0.6] },
        { id: 's2', erase: true, auto: false, radius: 0.01, hardness: 100, flow: 100, points: [0.7, 0.7, 0.71, 0.72] },
      ] },
      { ...radial, adjust: { ...radial.adjust, shadows: 25, clarity: -10 }, opacity: 80, invert: true },
      { ...linear, enabled: false },
    ],
  },
  leaksFx: { ...defaults, leaks: [leak, { ...newLightLeak(0.8, 0.2, 'streak'), seed: 0.5 }], fx: [fx] },
  // Healing brush strokes: a stroke with a chosen source, and a click with the engine's own pick.
  heal: { ...defaults, healSpots: [{ ...newHealSpot(0.4, 0.5, 0.01, [0.6, 0.5], 25), path: [0.4, 0.5, 0.41, 0.52] }, newHealSpot(0.9, 0.1, 0.0004, null)] },
  // Fields only the web had: the Swift port must keep them verbatim (luma contrast is a Swift field now, kept as a regression case).
  portrait: { ...defaults, portraitRetouch: 35, skinRetouch: 20 },
  webOnly: { ...defaults, exposure: 0.3, lumaContrast: 12 },
  untouched: { ...defaults },
};

const out: Record<string, string | null> = {};
for (const [k, v] of Object.entries(cases)) out[k] = encodeEdits(v as never, defaults as never);

const q = (s: string) => `#"""\n${s}\n"""#`;
let swift = '// Generated by tools/edits_fixtures/generate.ts from the web\'s Edits.ts: do not edit.\n';
swift += 'import Foundation\n\nenum EditsFixtures {\n';
swift += `    /** The defaults every fixture was encoded against (temperature 5200, tint 4, everything else the web's defaults). */\n`;
for (const [k, v] of Object.entries(out)) {
  swift += v === null ? `    static let ${k}: String? = nil\n` : `    static let ${k}: String? = ${q(v)}\n`;
}
swift += '}\n';
writeFileSync(new URL('../../ios/EngineTests/EditsFixtures.swift', import.meta.url), swift);
console.log(Object.entries(out).map(([k, v]) => `${k}: ${v ? v.length + ' bytes' : 'null'}`).join('\n'));
