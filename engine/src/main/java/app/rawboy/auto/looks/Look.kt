package app.rawboy.auto.looks

import app.rawboy.develop.DevelopParams

/**
 * A film look: one of the bundled LUTs plus adjustments added on top of the auto
 * develop. Deltas are in slider units (see [DevelopParams]); all are scaled by Strength.
 */
data class Look(
    val id: String,
    val name: String,
    /** Bundled LUT file in luts/, or null for none. */
    val lutFile: String?,
    val lutAmount: Float = 100f,
    val exposure: Float = 0f,
    val contrast: Float = 0f,
    val saturation: Float = 0f,
    val highlights: Float = 0f,
    val blacks: Float = 0f,
    val whites: Float = 0f,
    val grain: Float = 0f,
    val bloom: Float = 0f,
    val highpass: Float = 0f,
    val vignette: Float = 0f,
    /** Kelvin added to the white balance; + is warmer. */
    val warmth: Float = 0f,
    /** Skin retouch applied when the photo has a face. */
    val portraitRetouch: Float = 0f,
    val monochrome: Boolean = false,
    /** An unusual colour look (Redscale, Movie Green, Lagoon…): pickers list these in their own section. */
    val experimental: Boolean = false,
    /** Film stock id ([app.rawboy.film.FilmStocks]) rendered instead of AgX + LUT, or null. */
    val film: String? = null,
    /** Film grain and halation, 100 = the stock as formation.json describes it. */
    val filmGrain: Float = 100f,
    val halation: Float = 100f,
) {
    /** LutEntry id, as LutRepository names bundled LUTs. */
    val lutId: String? get() = lutFile?.let { "asset:luts/$it" }

    /** The picker section this look is listed in. */
    val group: LookGroup get() = when {
        monochrome -> LookGroup.MONOCHROME
        experimental -> LookGroup.EXPERIMENTAL
        else -> LookGroup.COLOR
    }
}

/** The pickers' sections of looks and bundled LUTs, in the order they are shown. */
enum class LookGroup(val label: String) {
    COLOR("Color"),
    EXPERIMENTAL("Experimental"),
    MONOCHROME("Black & white"),
}

